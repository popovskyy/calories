// ─────────────────────────── Еволюція маскота ───────────────────────────

/**
 * Стадії не продаються ніколи — тільки заробляються. Маскот IV стадії це не
 * куплений предмет, а доказ 250 днів дисципліни, і саме тому він цінний.
 */
export const EVOLUTION_STAGES = [
  { stage: 1, nameUk: "Новачок", inTargetDays: 0, streak: 0 },
  { stage: 2, nameUk: "Загартований", inTargetDays: 30, streak: 21 },
  { stage: 3, nameUk: "Ветеран", inTargetDays: 100, streak: 60 },
  { stage: 4, nameUk: "Легенда", inTargetDays: 250, streak: 180 },
] as const;

export type EvolutionStage = 1 | 2 | 3 | 4;

/** Стадія = найвища, чию умову виконано (досить будь-якої з двох). */
export function computeEvolutionStage(
  totalInTargetDays: number,
  maxStreak: number,
): EvolutionStage {
  let stage: EvolutionStage = 1;
  for (const s of EVOLUTION_STAGES) {
    if (totalInTargetDays >= s.inTargetDays || maxStreak >= s.streak) {
      stage = s.stage as EvolutionStage;
    }
  }
  return stage;
}
