import { describe, expect, it } from "vitest";
import {
  humanDate,
  lastNDays,
  shiftYMD,
  shortDate,
  weekDays,
  weekIndex,
  weekStartYMD,
  weekdayShort,
} from "@/lib/date";

/**
 * Увесь застосунок рахує дні рядками YYYY-MM-DD, а «сьогодні» бере в Києві.
 * Якщо ці хелпери зсунуться на день, поїде все одразу: квести, стрік, вікно
 * тижневого звіту, вісь графіка ваги.
 */
describe("shiftYMD", () => {
  it("рухається вперед і назад", () => {
    expect(shiftYMD("2026-08-02", 1)).toBe("2026-08-03");
    expect(shiftYMD("2026-08-02", -1)).toBe("2026-08-01");
    expect(shiftYMD("2026-08-02", 0)).toBe("2026-08-02");
  });

  it("переходить через межу місяця і року", () => {
    expect(shiftYMD("2026-01-31", 1)).toBe("2026-02-01");
    expect(shiftYMD("2026-12-31", 1)).toBe("2027-01-01");
    expect(shiftYMD("2027-01-01", -1)).toBe("2026-12-31");
  });

  it("знає високосний рік", () => {
    expect(shiftYMD("2028-02-28", 1)).toBe("2028-02-29");
    expect(shiftYMD("2026-02-28", 1)).toBe("2026-03-01");
  });

  it("не губить день на переходах літнього часу в Києві", () => {
    // Годинники переводять 2026-03-29 і 2026-10-25. YMD парситься як
    // UTC-північ саме заради цього — арифметика днів має лишатись цілою.
    expect(shiftYMD("2026-03-28", 1)).toBe("2026-03-29");
    expect(shiftYMD("2026-03-29", 1)).toBe("2026-03-30");
    expect(shiftYMD("2026-10-24", 1)).toBe("2026-10-25");
    expect(shiftYMD("2026-10-25", 1)).toBe("2026-10-26");
  });
});

describe("weekStartYMD", () => {
  it("тиждень Пн–Нд: понеділок лишається собою", () => {
    expect(weekStartYMD("2026-08-03")).toBe("2026-08-03"); // Пн
  });

  it("неділя належить ПОПЕРЕДНЬОМУ понеділку", () => {
    // Класичний off-by-one: у JS getDay() неділя = 0, і наївна арифметика
    // відкидає її у наступний тиждень.
    expect(weekStartYMD("2026-08-09")).toBe("2026-08-03");
  });

  it("кожен день тижня зводиться до того самого понеділка", () => {
    const monday = "2026-08-03";
    for (let i = 0; i < 7; i++) {
      expect(weekStartYMD(shiftYMD(monday, i))).toBe(monday);
    }
  });

  it("субота і неділя не розʼїжджаються по різних тижнях", () => {
    expect(weekStartYMD("2026-08-08")).toBe(weekStartYMD("2026-08-09"));
  });
});

describe("weekDays", () => {
  it("сім днів від понеділка до неділі, за зростанням", () => {
    const days = weekDays("2026-08-03");
    expect(days).toEqual([
      "2026-08-03",
      "2026-08-04",
      "2026-08-05",
      "2026-08-06",
      "2026-08-07",
      "2026-08-08",
      "2026-08-09",
    ]);
  });

  it("останній день тижня — неділя", () => {
    expect(weekdayShort(weekDays("2026-08-03")[6]!)).toBe("Нд");
  });
});

describe("lastNDays", () => {
  it("закінчується вказаним днем включно, від найстарішого", () => {
    expect(lastNDays("2026-08-03", 3)).toEqual([
      "2026-08-01",
      "2026-08-02",
      "2026-08-03",
    ]);
  });

  it("один день — це сам день", () => {
    expect(lastNDays("2026-08-03", 1)).toEqual(["2026-08-03"]);
  });
});

describe("weekIndex", () => {
  it("сусідні тижні дають сусідні індекси", () => {
    const a = weekIndex("2026-08-03");
    expect(weekIndex("2026-08-10")).toBe(a + 1);
    expect(weekIndex("2026-07-27")).toBe(a - 1);
  });

  it("той самий тиждень — той самий індекс (ротація стабільна)", () => {
    expect(weekIndex("2026-08-03")).toBe(weekIndex(weekStartYMD("2026-08-07")));
  });
});

describe("підписи дат", () => {
  it("shortDate і humanDate беруть саме вказану дату", () => {
    expect(shortDate("2026-08-03")).toBe("3 сер");
    expect(humanDate("2026-08-03")).toBe("Пн, 3 сер");
  });

  it("перше число місяця не зʼїжджає на попередній", () => {
    expect(shortDate("2026-03-01")).toBe("1 бер");
  });
});
