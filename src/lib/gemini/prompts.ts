export function profileBlock(p: UserProfile): string {
  const level = (p.level === "beginner" || p.level === "advanced" ? p.level : "intermediate") as AthleteLevel;
  const sex = p.sex === "female" ? "жінка" : "чоловік";
  return [
    `Ім'я: ${p.name}`,
    `${sex}, ${p.age} р., зріст ${p.heightCm} см, вага ${p.weightKg} кг`,
    `Ціль: ${p.goal}`,
    `Обмеження / здоров'я: ${p.limitations || "немає"}`,
    `Рівень підготовки: ${LEVEL_LABEL[level]} — ${LEVEL_RULES[level]}`,
    `Що атлет уже робить сам (фіксоване навантаження, не дублюй і не підміняй): ${p.routine?.trim() || "не вказано"}`,
  ].join("\n");
}

export interface AliasedEquipment {
  alias: string;
  item: Equipment;
}

const CATEGORY_HINT: Record<string, string> = {
  strength: "силовий (ОБОВ'ЯЗКОВО використати в основних блоках тижня)",
  cardio: "кардіо",
  mobility: "мобіліті",
  other: "інше",
};

export function equipmentBlock(list: AliasedEquipment[]): string {
  if (list.length === 0) {
    return "(інвентарю немає — лише власна вага та підлога; equipmentIds завжди [])";
  }
  return list
    .map(({ alias, item }) => {
      const parts = [`${alias}: ${item.name}`];
      if (item.detail) parts.push(item.detail);
      parts.push(`категорія: ${CATEGORY_HINT[item.category] ?? item.category}`);
      if (item.adjustable) {
        const cur = item.weightKg ?? item.maxWeightKg;
        parts.push(
          cur != null
            ? `регульована вага, зараз доступно до ${cur} кг` +
                (item.maxWeightKg != null && item.maxWeightKg !== cur ? ` (макс. ${item.maxWeightKg} кг)` : "")
            : "регульована вага",
        );
      }
      return `- ${parts.join(" | ")}`;
    })
    .join("\n");
}

/** Що саме є в інвентарі за описом (турнік, бруси), щоб модель ставила справжні підтягування й віджимання на брусах. */
export function capabilityBlock(list: AliasedEquipment[]): string {
  const caps = detectCapabilities(list.map(({ item }) => `${item.name} ${item.detail ?? ""}`).join(" "));
  const lines: string[] = [];
  if (caps.pullBar) {
    lines.push("- ТУРНІК є (зазначено в описі інвентарю): став повні підтягування різними хватами (середній, широкий, зворотний), вис; австралійські — лише як полегшення для новачка.");
  }
  if (caps.dipBars) {
    lines.push("- БРУСИ є (зазначено в описі інвентарю): став віджимання на брусах (dips), підйоми ніг в упорі на брусах; назви вправу «Віджимання на брусах».");
  }
  return lines.length ? lines.join("\n") : "(особливих можливостей понад перелік вище немає)";
}

