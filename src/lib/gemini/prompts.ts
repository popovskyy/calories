export function scanUserPrompt(existingNames: string[], photoCount: number): string {
  const have = existingNames.length ? existingNames.map((n) => `- ${n}`).join("\n") : "(порожньо)";
  return `Фото: ${photoCount}. Розпізнай тренувальний інвентар.\n\nВже є в інвентарі:\n${have}`;
}

export function profileBlock(p: UserProfile): string {
  const sex = p.sex === "female" ? "жінка" : "чоловік";
  return [
    `Ім'я: ${p.name}`,
    `${sex}, ${p.age} р., зріст ${p.heightCm} см, вага ${p.weightKg} кг`,
    `Ціль: ${p.goal}`,
    `Обмеження / здоров'я: ${p.limitations || "немає"}`,
  ].join("\n");
}

export interface AliasedEquipment {
  alias: string;
  item: Equipment;
}

export function equipmentBlock(list: AliasedEquipment[]): string {
  if (list.length === 0) {
    return "(інвентарю немає — лише власна вага та підлога; equipmentIds завжди [])";
  }
  return list
    .map(({ alias, item }) => {
      const parts = [`${alias}: ${item.name}`];
      if (item.detail) parts.push(item.detail);
      parts.push(`категорія: ${item.category}`);
      if (item.adjustable) {
        const cur = item.weightKg ?? item.maxWeightKg;
        parts.push(
          cur != null
            ? `регульована вага, зараз доступно до ${cur} кг` +
                (item.maxWeightKg != null && item.maxWeightKg !== cur ? ` (макс. ${item.maxWeightKg} кг)` : "")
            : "регульована вага",
        );
      }
      return `- ${parts.join(" | ")}`;
    })
    .join("\n");
}

